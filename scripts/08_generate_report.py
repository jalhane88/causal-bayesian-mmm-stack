    """
    report_path = "data/EXECUTIVE_MARKETING_REPORT.md"
    
    # Load budget optimization summary if available
    opt_file = "data/optimized_budget_allocation.csv"
    if os.path.exists(opt_file):
        opt_df = pd.read_csv(opt_file)
        opt_meta = opt_df['meta_allocation'].iloc[0]
        opt_google = opt_df['google_allocation'].iloc[0]
        opt_tv = opt_df['tv_allocation'].iloc[0]
        total_budget = opt_df['total_budget'].iloc[0]
    else:
        opt_meta, opt_google, opt_tv, total_budget = 21500.0, 27500.0, 1000.0, 50000.0

    report_content = f"""# Executive Marketing Measurement & Strategy Report

